"""Pydantic output contracts for advisory LLM enrichment of feasibility agents.

These are separate from FeasibilityRequest/ReviewRequest: those models validate
API input. AgentLLMInsight validates only the narrative advisory generated by an LLM.
"""
from pydantic import BaseModel, ConfigDict, Field

class AgentLLMInsight(BaseModel):
    """Constrained, advisory-only narrative; never authoritative clinical approval."""

    model_config = ConfigDict(extra="forbid")

    summary: str = Field(
        description="Concise summary grounded only in the supplied deterministic result."
    )
    qualitative_risks: list[str] = Field(
        default_factory=list,
        description="Potential operational or data-quality risks supported by supplied facts."
    )
    recommended_checks: list[str] = Field(
        default_factory=list,
        description="Checks a qualified human reviewer should consider; not medical advice."
    )
    uncertainty_notes: list[str] = Field(
        default_factory=list,
        description="Explicit limitations or missing evidence in the supplied result."
    )
